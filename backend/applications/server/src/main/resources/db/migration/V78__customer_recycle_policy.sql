CREATE TABLE admissions.customer_recycle_policy (
  tenant_id uuid NOT NULL REFERENCES identity.tenant(id),
  school_id uuid NOT NULL,
  school_kind varchar(20) NOT NULL DEFAULT 'SCHOOL' CHECK (school_kind='SCHOOL'),
  enabled boolean NOT NULL DEFAULT false,
  inactivity_days integer NOT NULL DEFAULT 7 CHECK (inactivity_days BETWEEN 1 AND 365),
  assignment_age_enabled boolean NOT NULL DEFAULT false,
  assignment_age_days integer NOT NULL DEFAULT 15 CHECK (assignment_age_days BETWEEN 1 AND 365),
  first_day_no_contact_enabled boolean NOT NULL DEFAULT false,
  first_day_cutoff time NOT NULL DEFAULT '23:59',
  version bigint NOT NULL DEFAULT 0,
  updated_by uuid,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (tenant_id,school_id),
  FOREIGN KEY (tenant_id,school_id,school_kind)
    REFERENCES organization.unit(tenant_id,id,kind)
);

CREATE TABLE admissions.customer_recycle_policy_request (
  tenant_id uuid NOT NULL REFERENCES identity.tenant(id),
  actor_id uuid NOT NULL,
  request_id uuid NOT NULL,
  school_id uuid NOT NULL,
  policy_version bigint NOT NULL,
  fingerprint varchar(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (tenant_id,actor_id,request_id),
  FOREIGN KEY (tenant_id,school_id)
    REFERENCES admissions.customer_recycle_policy(tenant_id,school_id)
);

