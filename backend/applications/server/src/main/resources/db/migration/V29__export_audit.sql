-- 经营数据导出：收款、报名、课次导出都要留痕（导出是独立动作，不能只靠查询权限推断）。
ALTER TABLE audit.funds_event DROP CONSTRAINT funds_event_action_check;
ALTER TABLE audit.funds_event
  ADD CHECK(action IN ('RECEIPT_CONFIRMED','RECEIPT_VOIDED','ALLOCATION_CREATED','ALLOCATION_RELEASED','REFUND_REBALANCED','RESERVATION_CREATED','CASH_REFUND_PAID','RESERVATION_RELEASED','RECEIPTS_EXPORTED'));

ALTER TABLE audit.enrollment_event DROP CONSTRAINT enrollment_event_action_check;
ALTER TABLE audit.enrollment_event
  ADD CHECK(action IN ('ENROLLMENT_CREATED','ENROLLMENT_APPROVED','HOURS_CANCELLED','DISCOUNT_ADDED','ENROLLMENTS_EXPORTED'));

ALTER TABLE audit.teaching_event DROP CONSTRAINT teaching_event_action_check;
ALTER TABLE audit.teaching_event
  ADD CHECK(action IN ('CLASS_CREATED','CLASS_MEMBER_ADDED','CLASS_CLOSED','LESSON_CREATED','LESSON_PUBLISHED','ATTENDANCE_CONFIRMED','LESSON_CLOSED','LESSONS_EXPORTED'));
