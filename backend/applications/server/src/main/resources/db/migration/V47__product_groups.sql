-- REV-010: school-scoped, optional product grouping; product pricing snapshots remain immutable.
CREATE TABLE product.product_group (
  id uuid PRIMARY KEY DEFAULT uuidv7(),
  tenant_id uuid NOT NULL REFERENCES identity.tenant(id),
  school_id uuid NOT NULL,
  school_kind varchar(20) NOT NULL DEFAULT 'SCHOOL' CHECK(school_kind='SCHOOL'),
  name varchar(100) NOT NULL CHECK(length(trim(name))>0),
  active boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(tenant_id,id),
  UNIQUE(tenant_id,school_id,id),
  UNIQUE(tenant_id,school_id,name),
  FOREIGN KEY(tenant_id,school_id,school_kind) REFERENCES organization.unit(tenant_id,id,kind)
);
CREATE INDEX product_group_school ON product.product_group(tenant_id,school_id,id);
ALTER TABLE product.product ADD COLUMN group_id uuid;
ALTER TABLE product.product ADD CONSTRAINT product_group_school_fk
  FOREIGN KEY(tenant_id,school_id,group_id)
  REFERENCES product.product_group(tenant_id,school_id,id);
CREATE INDEX product_group_products ON product.product(tenant_id,school_id,group_id,id);
ALTER TABLE product.product_group ENABLE ROW LEVEL SECURITY;
ALTER TABLE product.product_group FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_scope ON product.product_group
 USING (tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid)
 WITH CHECK (tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid);
GRANT SELECT,INSERT,UPDATE ON product.product_group TO ts_app;

ALTER TABLE product.creation_request DROP CONSTRAINT creation_request_kind_check;
ALTER TABLE product.creation_request ADD CHECK(kind IN ('CURRICULUM','PRODUCT','PRICE_VERSION','PRODUCT_GROUP'));
