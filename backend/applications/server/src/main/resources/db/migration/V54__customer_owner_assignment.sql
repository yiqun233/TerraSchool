CREATE TABLE admissions.customer_assignment_request (
 tenant_id uuid NOT NULL, actor_id uuid NOT NULL, request_id uuid NOT NULL,
 customer_id uuid NOT NULL, fingerprint varchar(64) NOT NULL, reason varchar(300) NOT NULL,
 PRIMARY KEY(tenant_id,actor_id,request_id),
 FOREIGN KEY(tenant_id,customer_id) REFERENCES admissions.customer(tenant_id,id)
);
ALTER TABLE admissions.customer_assignment_request ENABLE ROW LEVEL SECURITY;
