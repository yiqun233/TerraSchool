CREATE POLICY tenant_scope ON admissions.customer_assignment_request
 USING(tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid)
 WITH CHECK(tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid);
GRANT SELECT,INSERT ON admissions.customer_assignment_request TO ts_app;

