-- REV-009: Convert an owned lead into a student profile without merging archives.
CREATE TABLE admissions.customer_student_link (
  tenant_id uuid NOT NULL,
  customer_id uuid NOT NULL,
  student_id uuid NOT NULL,
  school_id uuid NOT NULL,
  owner_id uuid NOT NULL,
  request_id uuid NOT NULL,
  fingerprint varchar(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (tenant_id, customer_id),
  UNIQUE (tenant_id, owner_id, request_id),
  FOREIGN KEY (tenant_id, customer_id) REFERENCES admissions.customer(tenant_id, id),
  FOREIGN KEY (tenant_id, student_id) REFERENCES archive.student(tenant_id, id),
  FOREIGN KEY (tenant_id, school_id) REFERENCES organization.unit(tenant_id, id),
  FOREIGN KEY (tenant_id, owner_id) REFERENCES identity.account(tenant_id, id)
);
CREATE INDEX customer_student_link_student ON admissions.customer_student_link(tenant_id, student_id);

ALTER TABLE admissions.customer_student_link ENABLE ROW LEVEL SECURITY;
ALTER TABLE admissions.customer_student_link FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_scope ON admissions.customer_student_link
  USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);
GRANT SELECT, INSERT ON admissions.customer_student_link TO ts_app;

