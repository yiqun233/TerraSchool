ALTER TABLE admissions.customer
  ADD COLUMN merged_into_id uuid,
  ADD COLUMN merged_at timestamptz,
  ADD CONSTRAINT customer_merge_target_fk
    FOREIGN KEY(tenant_id,merged_into_id) REFERENCES admissions.customer(tenant_id,id),
  ADD CONSTRAINT customer_merge_state_check
    CHECK((merged_into_id IS NULL)=(merged_at IS NULL)),
  ADD CONSTRAINT customer_merge_not_self_check
    CHECK(merged_into_id IS NULL OR merged_into_id<>id);
CREATE INDEX customer_merged_into ON admissions.customer(tenant_id,merged_into_id) WHERE merged_into_id IS NOT NULL;
GRANT UPDATE(merged_into_id,merged_at,version) ON admissions.customer TO ts_app;

