-- 学校级整日停课日。排课预览与确认都读取同一权威数据；历史取消保留。
CREATE TABLE teaching.school_closure (
  id uuid PRIMARY KEY DEFAULT uuidv7(),
  tenant_id uuid NOT NULL,
  school_id uuid NOT NULL,
  closed_on date NOT NULL,
  reason varchar(200) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 0,
  created_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cancelled_by uuid,
  cancelled_at timestamptz,
  UNIQUE(tenant_id,id),
  FOREIGN KEY(tenant_id,school_id) REFERENCES organization.unit(tenant_id,id)
);
CREATE UNIQUE INDEX school_closure_active_unique ON teaching.school_closure(tenant_id,school_id,closed_on) WHERE active;
CREATE INDEX school_closure_active_date ON teaching.school_closure(tenant_id,school_id,closed_on) WHERE active;

ALTER TABLE teaching.school_closure ENABLE ROW LEVEL SECURITY;
ALTER TABLE teaching.school_closure FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_scope ON teaching.school_closure
 USING (tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid)
 WITH CHECK (tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid);
GRANT SELECT,INSERT,UPDATE ON teaching.school_closure TO ts_app;

