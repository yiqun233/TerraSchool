-- REV-009: independently authorized, audited, same-school student ownership.
ALTER TABLE archive.student ADD COLUMN owner_id uuid;
ALTER TABLE archive.student
  ADD CONSTRAINT student_owner_fk FOREIGN KEY(tenant_id,owner_id)
  REFERENCES identity.account(tenant_id,id);
GRANT UPDATE(owner_id,version,updated_at) ON archive.student TO ts_app;

CREATE TABLE archive.student_owner_assignment (
  id uuid PRIMARY KEY DEFAULT uuidv7(),
  tenant_id uuid NOT NULL,
  student_id uuid NOT NULL,
  from_account_id uuid,
  to_account_id uuid NOT NULL,
  reason varchar(200) NOT NULL CHECK(length(trim(reason))>0),
  actor_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(tenant_id,id),
  FOREIGN KEY(tenant_id,student_id) REFERENCES archive.student(tenant_id,id),
  FOREIGN KEY(tenant_id,from_account_id) REFERENCES identity.account(tenant_id,id),
  FOREIGN KEY(tenant_id,to_account_id) REFERENCES identity.account(tenant_id,id),
  FOREIGN KEY(tenant_id,actor_id) REFERENCES identity.account(tenant_id,id)
);
CREATE INDEX student_owner_assignment_history
  ON archive.student_owner_assignment(tenant_id,student_id,created_at,id);
ALTER TABLE archive.student_owner_assignment ENABLE ROW LEVEL SECURITY;
ALTER TABLE archive.student_owner_assignment FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_scope ON archive.student_owner_assignment
  USING(tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid)
  WITH CHECK(tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid);
GRANT SELECT,INSERT ON archive.student_owner_assignment TO ts_app;

CREATE TABLE archive.student_assignment_request (
  tenant_id uuid NOT NULL,
  actor_id uuid NOT NULL,
  request_id uuid NOT NULL,
  student_id uuid NOT NULL,
  fingerprint varchar(64) NOT NULL,
  PRIMARY KEY(tenant_id,actor_id,request_id),
  FOREIGN KEY(tenant_id,actor_id) REFERENCES identity.account(tenant_id,id),
  FOREIGN KEY(tenant_id,student_id) REFERENCES archive.student(tenant_id,id)
);
ALTER TABLE archive.student_assignment_request ENABLE ROW LEVEL SECURITY;
ALTER TABLE archive.student_assignment_request FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_scope ON archive.student_assignment_request
  USING(tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid)
  WITH CHECK(tenant_id=nullif(current_setting('app.tenant_id',true),'')::uuid);
GRANT SELECT,INSERT ON archive.student_assignment_request TO ts_app;

